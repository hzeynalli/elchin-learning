#!/usr/bin/env node
// Builds schema/seed/0001_skills.sql from data/*.json: the canonical skills table (102 skills) with planned_month from
// data/scope_sequence.json, aliases from data/qsi_crosswalk.json, fluency flags and MAP areas. Idempotent (upsert).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const J = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const files = ['data/skills_math_ccss.json', 'data/skills_reading.json', 'data/skills_language_usage.json', 'data/skills_science.json'];
const scope = J('data/scope_sequence.json').months;
const cross = J('data/qsi_crosswalk.json').math;
const FLUENCY = new Set(['G4.OA.F', '5.FLU']);
const MAP_AREA = {
  Mathematics: (s) => (/Fraction|Number|Fluency/.test(s.strand) ? 'Number and Operations' : /Algebraic|practices/i.test(s.strand) ? 'Operations and Algebraic Thinking' : /Measurement/.test(s.strand) ? 'Measurement and Data' : 'Geometry'),
  Reading: (s) => (/Literary/.test(s.strand) ? 'Literary Text' : /Informational/.test(s.strand) ? 'Informational Text' : /Vocabulary/.test(s.strand) ? 'Vocabulary Acquisition and Use' : 'Foundational / Habit'),
  'Language Usage': (s) => (/Grammar/.test(s.strand) ? 'Grammar and Usage' : /Mechanics/.test(s.strand) ? 'Mechanics' : 'Writing: Plan, Organize, Develop, Revise, Research'),
  Science: (s) => (/Physical/.test(s.strand) ? 'Physical Science' : /Life/.test(s.strand) ? 'Life Science' : /Earth/.test(s.strand) ? 'Earth and Space Science' : 'Science Practices'),
};
const plannedMonth = (id) => {
  for (const [m, ids] of Object.entries(scope)) for (const x of ids) { if (x === id) return m; if (x.endsWith('*') && id.startsWith(x.slice(0, -1))) return m; }
  return null;
};
const aliases = {}; for (const [q, ids] of Object.entries(cross)) for (const id of ids) (aliases[id] ??= []).push(q);
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `'{${(a || []).map((x) => `"${String(x).replace(/"/g, '\\"')}"`).join(',')}}'`;

const rows = [];
for (const f of files) for (const s of J(f).skills) {
  rows.push(`(${q(s.id)}, ${q(s.subject)}, ${q(s.strand)}, ${q(s.qsi_unit)}, ${q(s.standard)}, ${q(s.name)}, ${s.grade}, ${arr(s.prerequisites)}, ${s.priority}, ${arr(aliases[s.id])}, ${q(plannedMonth(s.id))}, ${FLUENCY.has(s.id)}, ${q(MAP_AREA[s.subject](s))})`);
}
const sql = `-- generated by scripts/build-seed-sql.js — do not edit by hand\ninsert into skills (id, subject, strand, qsi_unit, standard, name, grade, prerequisites, priority, aliases, planned_month, fluency, map_area) values\n${rows.join(',\n')}\non conflict (id) do update set subject = excluded.subject, strand = excluded.strand, qsi_unit = excluded.qsi_unit, standard = excluded.standard, name = excluded.name, grade = excluded.grade, prerequisites = excluded.prerequisites, priority = excluded.priority, aliases = excluded.aliases, planned_month = excluded.planned_month, fluency = excluded.fluency, map_area = excluded.map_area;\n`;
mkdirSync(join(root, 'schema/seed'), { recursive: true });
writeFileSync(join(root, 'schema/seed/0001_skills.sql'), sql);
const ids = new Set(); let dup = 0; for (const f of files) for (const s of J(f).skills) { if (ids.has(s.id)) dup++; ids.add(s.id); }
const missingPrereq = []; for (const f of files) for (const s of J(f).skills) for (const p of s.prerequisites) if (!ids.has(p)) missingPrereq.push(`${s.id}→${p}`);
console.log(`skills: ${rows.length}, duplicates: ${dup}, dangling prerequisites: ${missingPrereq.length ? missingPrereq.join(' ') : 'none'}, priority-1: ${[...files].flatMap((f) => J(f).skills).filter((s) => s.priority === 1).length}`);
