#!/usr/bin/env node
// Bundles data/explanations/<skill_id>.md (one canonical explanation per priority-1 skill, docs/02 §2, AUDIT Judge 1)
// into worker/src/explanations.json so the coach can inject it into the system prompt. Also emits
// schema/seed/0003_explanations.sql for the owner-editable `explanations` table (DB row overrides the bundled text).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'data/explanations');
const out = {};
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')).sort() : [];
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const sql = ['-- generated by scripts/build-explanations.js'];
for (const f of files) {
  const id = f.replace(/\.md$/, '');
  const body = readFileSync(join(dir, f), 'utf8').trim();
  const words = body.split(/\s+/).length;
  if (words < 120) { console.error(`✗ ${id}: only ${words} words`); process.exitCode = 1; continue; }
  for (const h of ['## The idea', '## Worked example', '## Faded example', '## Anticipated errors', '## Representation sequence']) if (!body.includes(h)) { console.error(`✗ ${id}: missing "${h}"`); process.exitCode = 1; }
  out[id] = body;
  sql.push(`insert into explanations (skill_id, body) values (${q(id)}, ${q(body)}) on conflict (skill_id) do update set body = excluded.body, updated_at = now();`);
}
writeFileSync(join(root, 'worker/src/explanations.json'), JSON.stringify(out, null, 1) + '\n');
writeFileSync(join(root, 'schema/seed/0003_explanations.sql'), sql.join('\n') + '\n');
const p1 = ['skills_math_ccss', 'skills_reading', 'skills_language_usage', 'skills_science'].flatMap((f) => JSON.parse(readFileSync(join(root, `data/${f}.json`), 'utf8')).skills.filter((s) => s.priority === 1).map((s) => s.id));
const missing = p1.filter((id) => !out[id]);
console.log(`${Object.keys(out).length} explanations bundled; priority-1 skills without one: ${missing.length ? missing.join(', ') : 'none'}`);
