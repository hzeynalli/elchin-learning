#!/usr/bin/env node
// Turns the hand-written content in data/passages/*.json and data/items/*.json into schema/seed/0002_content.sql
// (passages + item_bank rows, verified=true). Runs the readability gate and item sanity checks first; refuses to emit
// SQL if anything fails. Idempotent: inserts skip stem hashes already present.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { checkPassage } from '../worker/src/readability.js';
import { stemHash, itemKey } from '../worker/src/items.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readAll = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8'))) : []);
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

const skills = new Set(['skills_math_ccss', 'skills_reading', 'skills_language_usage', 'skills_science'].flatMap((f) => JSON.parse(readFileSync(join(root, `data/${f}.json`), 'utf8')).skills.map((s) => s.id)));
let errors = 0;
const sql = ['-- generated by scripts/build-content-seed.js — do not edit by hand'];
const itemRows = [];

for (const file of readAll(join(root, 'data/passages'))) {
  for (const p of file.passages || []) {
    const tier = Math.max(...p.questions.map((x) => x.tier));
    const c = checkPassage(p.text, { tier: tier >= 3 ? 3 : 2 });
    if (!c.ok) { console.error(`✗ passage ${p.id}: ${c.problems.join('; ')}`); errors++; continue; }
    sql.push(`insert into passages (title, author, origin, genre, topic, text, word_count, fk_grade, lexile_est, questions)
select ${q(p.title)}, ${q(p.author || 'Elchin Learning (original)')}, ${q(p.origin)}, ${q(p.genre)}, ${q(p.topic)}, ${q(p.text)}, ${c.words}, ${c.fk_grade}, ${c.lexile_est}, ${j(p.questions)}
where not exists (select 1 from passages where title = ${q(p.title)});`);
    // bank rows reference the passage by title; the Worker attaches the text at serve time (keeps the seed small)
    p.questions.forEach((qq) => itemRows.push({ ...qq, passage_title: p.title, passage_ref: p.id, generated_by: 'human' }));
  }
}
for (const file of readAll(join(root, 'data/items'))) for (const it of file.items || []) itemRows.push({ ...it, generated_by: 'human' });

const seen = new Set();
let n = 0;
for (const it of itemRows) {
  if (!skills.has(it.skill_id)) { console.error(`✗ unknown skill ${it.skill_id}: ${it.stem?.slice(0, 50)}`); errors++; continue; }
  if (!it.stem || !it.format || !it.tier) { console.error(`✗ item missing fields: ${JSON.stringify(it).slice(0, 80)}`); errors++; continue; }
  if (it.format === 'mc4' && (!Array.isArray(it.options) || it.options.length !== 4 || new Set(it.options).size !== 4 || !/^[A-D]$/.test(it.answer))) { console.error(`✗ bad mc4: ${it.stem.slice(0, 60)}`); errors++; continue; }
  if (it.format === 'short_text' && !it.rubric && !it.answer) { console.error(`✗ short_text without rubric: ${it.stem.slice(0, 60)}`); errors++; continue; }
  if (it.format === 'fill_blank' && it.answer == null) { console.error(`✗ fill_blank without answer: ${it.stem.slice(0, 60)}`); errors++; continue; }
  if (!it.explanation) { console.error(`✗ item without explanation: ${it.stem.slice(0, 60)}`); errors++; continue; }
  const h = stemHash(itemKey(it));
  const key = `${it.skill_id}:${h}`;
  if (seen.has(key)) { console.error(`✗ duplicate item for ${it.skill_id}: ${it.stem.slice(0, 60)}`); errors++; continue; }
  seen.add(key);
  const { skill_id, tier, passage_ref, ...rest } = it;
  const item = { ...rest, skill_id, tier, verification: { ok: true, reason: 'hand-written, owner-reviewed' } };
  const itemSql = it.passage_title
    ? `jsonb_set(${j(item)}, '{passage_id}', to_jsonb((select id::text from passages where title = ${q(it.passage_title)} limit 1)))`
    : j(item);
  sql.push(`insert into item_bank (skill_id, tier, format, item, stem_hash, verified, used)
select ${q(skill_id)}, ${tier}, ${q(it.format)}, ${itemSql}, ${q(h)}, true, false
where not exists (select 1 from item_bank where skill_id = ${q(skill_id)} and stem_hash = ${q(h)});`);
  n++;
}
if (errors) { console.error(`\n${errors} problem(s) — no SQL written`); process.exit(1); }
writeFileSync(join(root, 'schema/seed/0002_content.sql'), sql.join('\n') + '\n');
const perSkill = {}; for (const it of itemRows) (perSkill[it.skill_id] ??= [0, 0, 0])[it.tier - 1]++;
console.log(`passages: ${sql.filter((s) => s.startsWith('insert into passages')).length}, items: ${n}`);
console.log(Object.entries(perSkill).sort().map(([k, v]) => `${k} ${v.join('/')}`).join('  '));
